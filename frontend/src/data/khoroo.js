/**
 * Дүүрэг тус бүрийн хорооны тоо (2026).
 * Хаягийн алдааг арилгахын тулд хороог гараар бичихгүй, жагсаалтаас
 * сонгоно — дүүрэг солиход жагсаалт нь автоматаар шинэчлэгдэнэ.
 */
export const KHOROO_COUNT = {
  БЗД: 43, // Баянзүрх
  СХД: 43, // Сонгинохайрхан
  БГД: 34, // Баянгол
  ХУД: 25, // Хан-Уул
  ЧД: 24, // Чингэлтэй
  СБД: 20, // Сүхбаатар
  НД: 8, // Налайх
  БНД: 5, // Багануур
  БХД: 2, // Багахангай
}

/** Тухайн дүүргийн хороодын жагсаалт: ['1', '2', … 'N'] */
export function khorooList(district) {
  const n = KHOROO_COUNT[district] ?? 0
  return Array.from({ length: n }, (_, i) => String(i + 1))
}
